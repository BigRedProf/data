	/// <summary>
	/// Captures golden bytes from the pre-BitStream <see cref="CodeWriter"/>.
	/// This program is the capture tool for <c>golden.txt</c>. It is not part of
	/// <c>Data.sln</c>. Run it from this directory before any BitStream change:
	/// <c>dotnet run -- golden.txt</c>.
	/// </summary>
	internal static class GenerateGoldenBytes
	{
		#region constants
		private static readonly Guid TapeSeriesId = new Guid("11111111-2222-3333-4444-555555555555");
		#endregion

		#region functions
		private static int Main(string[] args)
		{
			string outputPath = args.Length > 0 ? args[0] : "golden.txt";

			PiedPiper piedPiper = new PiedPiper();
			piedPiper.RegisterCorePackRats();
			piedPiper.DefineCoreTraits();

			StringBuilder manifest = new StringBuilder();
			manifest.AppendLine("# Golden bytes captured from CodeWriter before the BitStream change.");
			manifest.AppendLine("# Generated by tests/Golden/GenerateGoldenBytes.cs.");
			manifest.AppendLine("# Do not edit. Any later diff to this file fails review.");
			manifest.AppendLine();

			WriteRawSamples(manifest);
			WritePackRatSamples(manifest, piedPiper);
			WriteTapeSample(manifest);

			File.WriteAllText(outputPath, manifest.ToString().Replace("\r\n", "\n"));
			Console.WriteLine("Wrote " + outputPath);
			return 0;
		}

		private static void WriteRawSamples(StringBuilder manifest)
		{
			WriteRaw(
				manifest,
				"raw-mid-byte",
				new string[] { "WRITE 101" }
			);
			WriteRaw(
				manifest,
				"raw-zero-bit",
				new string[] { "WRITE -" }
			);
			WriteRaw(
				manifest,
				"raw-back-to-back",
				new string[]
				{
					"WRITE 101",
					"WRITE 01011",
					"WRITE -",
					"WRITE 1",
					"WRITE 1111000"
				}
			);
			WriteRaw(
				manifest,
				"raw-align-example",
				new string[]
				{
					"WRITE 101",
					"ALIGN",
					"WRITE 11110000"
				}
			);
			WriteRaw(
				manifest,
				"raw-flush-between-unaligned",
				new string[]
				{
					"WRITE 101",
					"FLUSH",
					"WRITE 11"
				}
			);
		}

		private static void WriteRaw(StringBuilder manifest, string name, string[] operations)
		{
			int bitLength = 0;
			byte[] bytes = Capture(
				delegate(CodeWriter writer)
				{
					foreach (string operation in operations)
						bitLength = ApplyOperation(writer, operation, bitLength);
				}
			);

			manifest.AppendLine("SAMPLE " + name);
			manifest.AppendLine("KIND raw");
			manifest.AppendLine("BIT_LENGTH " + bitLength.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine("HEX " + ToHex(bytes));
			foreach (string operation in operations)
				manifest.AppendLine("OP " + operation);
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static int ApplyOperation(CodeWriter writer, string operation, int bitLength)
		{
			if (operation == "ALIGN")
			{
				int remainder = bitLength % 8;
				if (remainder != 0)
					bitLength += 8 - remainder;

				writer.AlignToNextByteBoundary();
				return bitLength;
			}

			if (operation == "FLUSH")
			{
				// CodeWriter has no Flush. The underlying stream does, and flushing
				// must not pad. Record the operation so the new writer is asked to
				// flush at the same point.
				return bitLength;
			}

			if (operation.StartsWith("WRITE ", StringComparison.Ordinal))
			{
				string bits = operation.Substring("WRITE ".Length);
				Code code = bits == "-" ? new Code(0) : new Code(bits);
				writer.WriteCode(code);
				return bitLength + code.Length;
			}

			throw new InvalidOperationException("Unknown operation '" + operation + "'.");
		}

		private static void WritePackRatSamples(StringBuilder manifest, PiedPiper piedPiper)
		{
			WritePackRat(manifest, piedPiper, "packrat-boolean", CoreSchema.Boolean, "bool", "true", true);
			WritePackRat(manifest, piedPiper, "packrat-byte", CoreSchema.Byte, "byte", "165", (byte)165);
			WritePackRat(manifest, piedPiper, "packrat-code-mid-byte", CoreSchema.Code, "code", "10101", new Code("10101"));
			WritePackRat(manifest, piedPiper, "packrat-code-zero-bit", CoreSchema.Code, "code", "-", new Code(0));
			WritePackRat(
				manifest,
				piedPiper,
				"packrat-datum",
				CoreSchema.Datum,
				"datum",
				CoreSchema.Code + "|101",
				new Datum(CoreSchema.Code, new Code("101"))
			);

			DateTime utc = new DateTime(2020, 1, 2, 3, 4, 5, DateTimeKind.Utc);
			WritePackRat(
				manifest,
				piedPiper,
				"packrat-datetime-with-kind",
				CoreSchema.DateTimeWithKind,
				"datetime",
				utc.Ticks.ToString(CultureInfo.InvariantCulture) + "|Utc",
				utc
			);

			DateTime unspecified = new DateTime(2020, 1, 2, 3, 4, 5, DateTimeKind.Unspecified);
			WritePackRat(
				manifest,
				piedPiper,
				"packrat-datetime-without-kind",
				CoreSchema.DateTimeWithoutKind,
				"datetime",
				unspecified.Ticks.ToString(CultureInfo.InvariantCulture) + "|Unspecified",
				unspecified
			);

			WritePackRat(manifest, piedPiper, "packrat-double", CoreSchema.Double, "double", "1.5", 1.5d);
			WritePackRat(manifest, piedPiper, "packrat-ewn31", CoreSchema.EfficientWholeNumber31, "ewn31", "100", 100);

			FlexDatum flexDatum = new FlexDatumBuilder(piedPiper)
				.AddTrait<string>(CoreTrait.Name, "golden")
				.Build();
			WritePackRat(
				manifest,
				piedPiper,
				"packrat-flexdatum",
				CoreSchema.FlexDatum,
				"flexdatum-name",
				"golden",
				flexDatum
			);

			Guid guid = new Guid("00112233-4455-6677-8899-aabbccddeeff");
			WritePackRat(manifest, piedPiper, "packrat-guid", CoreSchema.Guid, "guid", guid.ToString("D"), guid);
			WritePackRat(manifest, piedPiper, "packrat-int32", CoreSchema.Int32, "int32", "-123456", -123456);
			WritePackRat(manifest, piedPiper, "packrat-int64", CoreSchema.Int64, "int64", "1234567890123", 1234567890123L);
			WritePackRat(
				manifest,
				piedPiper,
				"packrat-multihash",
				CoreSchema.MultihashSchema,
				"multihash-sha256",
				"01020304",
				Multihash.FromBytes(new byte[] { 0x01, 0x02, 0x03, 0x04 }, MultihashAlgorithm.Sha256)
			);
			WritePackRat(manifest, piedPiper, "packrat-single", CoreSchema.Single, "single", "-2.25", -2.25f);
			WritePackRat(manifest, piedPiper, "packrat-text-ascii", CoreSchema.TextAscii, "text", "Cat", "Cat");
			WritePackRat(
				manifest,
				piedPiper,
				"packrat-texttrail",
				CoreSchema.TextTrail,
				"texttrail",
				"north/star",
				new TextTrail("north", "star")
			);
			WritePackRat(manifest, piedPiper, "packrat-text-utf8", CoreSchema.TextUtf8, "text", "héllo", "héllo");
			WritePackRat(manifest, piedPiper, "packrat-text-utf16", CoreSchema.TextUtf16, "text", "héllo", "héllo");
			WritePackRat(manifest, piedPiper, "packrat-text-utf32", CoreSchema.TextUtf32, "text", "héllo", "héllo");
			WritePackRat(manifest, piedPiper, "packrat-uvarint", CoreSchema.UnsignedVarInt, "uvarint", "300", 300);
			WritePackRat(manifest, piedPiper, "packrat-varint", CoreSchema.VarInt, "varint", "-2", -2);

			for (int width = 1; width <= 31; ++width)
			{
				string fieldName = "WholeNumber" + width.ToString(CultureInfo.InvariantCulture);
				FieldInfo? field = typeof(CoreSchema).GetField(fieldName);
				if (field == null)
					throw new InvalidOperationException("Missing schema " + fieldName);

				string? schemaId = (string?)field.GetValue(null);
				if (schemaId == null)
					throw new InvalidOperationException("Missing schema " + fieldName);
				int value = 1 << (width - 1);
				WritePackRat(
					manifest,
					piedPiper,
					"packrat-wholenumber-" + width.ToString(CultureInfo.InvariantCulture),
					schemaId,
					"wholenumber",
					value.ToString(CultureInfo.InvariantCulture),
					value
				);
			}
		}

		private static void WritePackRat(
			StringBuilder manifest,
			PiedPiper piedPiper,
			string name,
			string schemaId,
			string type,
			string value,
			object model
		)
		{
			Code exact = piedPiper.PackModel(model, schemaId);
			byte[] bytes = Capture(
				delegate(CodeWriter writer)
				{
					piedPiper.PackModel(writer, model, schemaId);
				}
			);

			byte[] exactBytes = exact.ToByteArray();
			if (exactBytes.Length != bytes.Length)
				throw new InvalidOperationException(name + " byte length mismatch.");

			for (int i = 0; i < bytes.Length; ++i)
			{
				if (exactBytes[i] != bytes[i])
					throw new InvalidOperationException(name + " byte mismatch at " + i.ToString(CultureInfo.InvariantCulture));
			}

			manifest.AppendLine("SAMPLE " + name);
			manifest.AppendLine("KIND packrat");
			manifest.AppendLine("SCHEMA " + schemaId);
			manifest.AppendLine("TYPE " + type);
			manifest.AppendLine("VALUE " + value);
			manifest.AppendLine("BIT_LENGTH " + exact.Length.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine("HEX " + ToHex(bytes));
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static void WriteTapeSample(StringBuilder manifest)
		{
			MemoryTapeProvider provider = new MemoryTapeProvider();
			Librarian librarian = new Librarian(provider);
			const string seriesName = "golden";
			const string seriesDescription = "multi-session unaligned";

			string[][] sessions = new string[][]
			{
				new string[] { "WRITE 101", "WRITE 0110" },
				new string[] { "WRITE -", "WRITE 11", "WRITE 10101" },
				new string[] { "WRITE 0", "WRITE 11110000" }
			};

			BackupWizard first = BackupWizard.CreateNew(
				librarian,
				TapeSeriesId,
				seriesName,
				seriesDescription
			);
			ApplySession(first, sessions[0]);

			BackupWizard second = BackupWizard.OpenExisting(librarian, TapeSeriesId);
			ApplySession(second, sessions[1]);

			BackupWizard third = BackupWizard.OpenExisting(librarian, TapeSeriesId);
			ApplySession(third, sessions[2]);

			IList<TapeUnit> tapes = librarian.FetchTapesInSeries(TapeSeriesId);

			manifest.AppendLine("SAMPLE tape-multi-session-unaligned");
			manifest.AppendLine("KIND tape");
			manifest.AppendLine("SERIES " + TapeSeriesId.ToString("D"));
			manifest.AppendLine("NAME " + seriesName);
			manifest.AppendLine("DESCRIPTION " + seriesDescription);
			foreach (string[] session in sessions)
			{
				manifest.AppendLine("SESSION");
				foreach (string operation in session)
					manifest.AppendLine("OP " + operation);
			}

			foreach (TapeUnit tape in tapes)
			{
				TapeLabel label = tape.ReadLabel();
				int bitLength = tape.Position;
				int byteLength = (bitLength + 7) / 8;
				byte[] content = byteLength == 0
					? Array.Empty<byte>()
					: provider.ReadTapeInternal(tape.Id, 0, byteLength);

				manifest.AppendLine(
					"TAPE " + label.SeriesNumber.ToString(CultureInfo.InvariantCulture)
					+ " BIT_LENGTH " + bitLength.ToString(CultureInfo.InvariantCulture)
					+ " HEX " + ToHex(content)
				);
			}

			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static void ApplySession(BackupWizard wizard, string[] operations)
		{
			foreach (string operation in operations)
			{
				if (!operation.StartsWith("WRITE ", StringComparison.Ordinal))
					throw new InvalidOperationException("Tape sessions only write.");

				string bits = operation.Substring("WRITE ".Length);
				Code code = bits == "-" ? new Code(0) : new Code(bits);
				wizard.Append(code);
			}

			wizard.Writer.Dispose();
		}

		private static byte[] Capture(Action<CodeWriter> write)
		{
			MemoryStream stream = new MemoryStream();
			using (CodeWriter writer = new CodeWriter(stream))
			{
				write(writer);
			}

			return stream.ToArray();
		}

		private static string ToHex(byte[] bytes)
		{
			if (bytes.Length == 0)
				return "-";

			StringBuilder builder = new StringBuilder(bytes.Length * 2);
			for (int i = 0; i < bytes.Length; ++i)
				builder.Append(bytes[i].ToString("x2", CultureInfo.InvariantCulture));

			return builder.ToString();
		}
		#endregion
	}
